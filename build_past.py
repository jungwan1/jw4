def esc(s: str) -> str:
    return html.escape(s, quote=True)


def render_new_card(card: dict) -> str:
    parts = ['<section class="card">']
    parts.append(f'<div class="r"><span class="ko">뜻: {esc(card["ko"])}</span></div>')
    parts.append(f'<div class="r"><span class="ko">러시아어</span><span class="ru">{esc(card["ru"])}</span></div>')
    parts.append(f'<div class="r"><span class="ko">한글 발음</span><span class="say">{esc(card["say"])}</span></div>')
    if card.get("pt"):
        parts.append(f'<p class="pt">{esc(card["pt"])}</p>')
    parts.append("</section>")
    return "\n".join(parts)


def extract_week_cards(path: Path) -> list[str]:
    text = path.read_text(encoding="utf-8")
    found = re.findall(r'<section class="card"><h3>\d+\.</h3>\s*(.*?)</section>', text, flags=re.S)
    cards = []
    for inner in found:
        cards.append('<section class="card">\n' + inner.strip() + "\n</section>")
    return cards


def all_existing_cards() -> list[str]:
    out: list[str] = []
    for name in WEEK_FILES:
        path = WEEK_DIR / name
        cards = extract_week_cards(path)
        if not cards:
            raise SystemExit(f"no sentence cards in {path}")
        # Within a week the original order is oldest-first, so reverse.
        out.extend(reversed(cards))
    return out


